"""lr-7a: after DigestCollision.lean has found `a` and `b`, declare a kernel constant `Kernels.Demo.model`
as `fun x => x + a` in one Lean file and `fun x => x + b` in another, and print the hash the claim reader
gives it (the code of `constJson` in tools/claim_reader.lean.in, copied below) and the item digest `tvr`
would compute from that constant alone (sha256 of its `name hash` line, as `check` does for a cone).
Usage: python3 -I work/digest_check.py   (reads work/DigestCollision.out; writes work/DigestCheck{A,B}.lean)
"""
import hashlib
import os
import re
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
TVA = os.path.abspath(os.path.join(HERE, *[os.pardir] * 5))
out = open(os.path.join(HERE, "DigestCollision.out")).read()
m = re.search(r"a = (\d+), b = (\d+)", out)
if not m:
    raise SystemExit("no collision in DigestCollision.out")
a, b = int(m.group(1)), int(m.group(2))

TEMPLATE = """import Lean
-- lr-7a, generated by work/digest_check.py: the kernel constant of one side of the collision.
open Lean Meta

namespace Kernels.Demo
/-- The model (a stand-in for a kernel's `model`). -/
def model : Nat → Nat := fun x => x + {n}
end Kernels.Demo

/-- As in tools/claim_reader.lean.in. -/
def normWs (s : String) : String := Id.run do
  let mut out : Array Char := #[]
  let mut sp := false
  for c in s.toList do
    if c.isWhitespace then sp := true
    else
      if sp && !out.isEmpty then out := out.push ' '
      sp := false
      out := out.push c
  return String.ofList out.toList

-- constJson's hash, as in tools/claim_reader.lean.in
#eval show MetaM Unit from do
  let env ← getEnv
  let n := `Kernels.Demo.model
  let some ci := env.find? n | throwError "missing"
  let vh : UInt64 := match ci with
    | .defnInfo v => mixHash v.value.hash (hash (toString v.value))
    | _ => 0
  let doc ← findDocString? env n
  let trusted := n.getRoot == `TVA
  let th := mixHash (mixHash ci.type.hash (hash (toString ci.type)))
    (if trusted then hash (normWs (doc.getD "")) else 0)
  IO.println s!"HASH {{n}} {{th}}-{{vh}}"
  IO.println s!"VALUE {{toString ci.value!}}"

#eval IO.println s!"RESULT Kernels.Demo.model 0 = {{Kernels.Demo.model 0}}"
"""
lines = {}
for side, n in (("A", a), ("B", b)):
    path = os.path.join(HERE, f"DigestCheck{side}.lean")
    open(path, "w").write(TEMPLATE.format(n=n))
    r = subprocess.run([os.path.expanduser("~/.elan/bin/lake"), "env", "lean", path], cwd=os.path.join(TVA, "lean"),
                       capture_output=True, text=True)
    text = r.stdout + r.stderr
    h = re.search(r"HASH (.*)", text).group(1)
    lines[side] = h
    print(f"{side}: model = fun x => x + {n}")
    print(f"   {re.search(r'RESULT (.*)', text).group(1)}")
    print(f"   constJson hash line: {h}")
    print(f"   item digest from this cone line (sha256): {hashlib.sha256(h.encode()).hexdigest()[:16]}")
print(f"the two cone lines are identical: {lines['A'] == lines['B']}")
