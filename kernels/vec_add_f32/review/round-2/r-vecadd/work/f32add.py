"""r-vecadd, round 2, third filing: reference float32 sums for Post's `FloatV.add`.

Prints a Lean file (AddCheck3.lean) that evaluates `TVA.FloatV.add` on float32 bit patterns and
compares each result with two references computed here, independently of the library:
  * numpy's float32 addition (IEEE, round to nearest even, subnormals kept, on x86-64);
  * an exact rounding of the rational sum to float32 (round half to even), written below.
Both references must agree with each other before a case is emitted. NaN results are compared
as "is a NaN" only, since Post compares up to NaN payload (FloatV.NaNEq).

Run: python3 -I f32add.py > AddCheck3.lean
"""
import random
import struct
from fractions import Fraction

import numpy as np

MAXVAL = Fraction((2 ** 24 - 1) * 2 ** 104)


def f32_of(p):
    return np.frombuffer(struct.pack("<I", p), dtype=np.float32)[0]


def pat_of(x):
    return struct.unpack("<I", np.float32(x).tobytes())[0]


def is_nan(p):
    return (p >> 23) & 0xFF == 0xFF and p & 0x7FFFFF != 0


def is_inf(p):
    return (p >> 23) & 0xFF == 0xFF and p & 0x7FFFFF == 0


def value(p):
    s = -1 if p >> 31 else 1
    e = (p >> 23) & 0xFF
    m = p & 0x7FFFFF
    if e == 0:
        return s * Fraction(m, 2 ** 149)
    return s * Fraction(2 ** 23 + m) * Fraction(2) ** (e - 150)


def round_f32(q):
    """The float32 pattern nearest to the nonzero rational q, ties to even."""
    sign = 0x80000000 if q < 0 else 0
    a = -q if q < 0 else q
    e = a.numerator.bit_length() - a.denominator.bit_length()
    if Fraction(2) ** e > a:
        e -= 1
    while Fraction(2) ** (e + 1) <= a:
        e += 1
    E = max(e, -126)
    Q = E - 23
    t = a / Fraction(2) ** Q
    N = t.numerator // t.denominator
    r = t - N
    if r > Fraction(1, 2) or (r == Fraction(1, 2) and N % 2 == 1):
        N += 1
    if N == 2 ** 24:
        N, Q = 2 ** 23, Q + 1
    if Fraction(N) * Fraction(2) ** Q > MAXVAL:
        return sign | 0x7F800000
    if N < 2 ** 23:
        return sign | N
    return sign | ((Q + 23 + 127) << 23) | (N - 2 ** 23)


def ref_exact(x, y):
    if is_nan(x) or is_nan(y):
        return None
    if is_inf(x) or is_inf(y):
        if is_inf(x) and is_inf(y) and (x >> 31) != (y >> 31):
            return None
        return x if is_inf(x) else y
    q = value(x) + value(y)
    if q == 0:
        return 0x80000000 if (x >> 31) and (y >> 31) else 0
    return round_f32(q)


def ref_numpy(x, y):
    with np.errstate(all="ignore"):
        r = pat_of(f32_of(x) + f32_of(y))
    return None if is_nan(r) else r


def rand_pat(rng):
    kind = rng.random()
    if kind < 0.6:
        e = rng.randrange(1, 255)
    elif kind < 0.8:
        e = rng.choice([0, 1, 2, 253, 254])
    else:
        e = rng.randrange(100, 160)
    return (rng.randrange(2) << 31) | (e << 23) | rng.randrange(2 ** 23)


SPECIAL = [
    (0x3F800000, 0x33800000),  # 1 + 2^-24: a tie, to even (1.0)
    (0x3F800001, 0x33800000),  # (1 + 2^-23) + 2^-24: a tie, to even (up)
    (0x3F800000, 0x34000000),  # 1 + 2^-23: exact
    (0x3F800000, 0x3A800000),  # 1 + 2^-10: exact in float32, 1.0 in bfloat16
    (0x7F7FFFFF, 0x7F7FFFFF),  # maxVal + maxVal: +inf
    (0x7F7FFFFF, 0x73000000),  # maxVal + 2^103 (half an ulp): a tie, to +inf
    (0x7F7FFFFF, 0x72FFFFFF),  # maxVal + just under half an ulp: maxVal
    (0x7F800000, 0xFF800000),  # inf + -inf: NaN
    (0x7F800000, 0x3F800000),  # inf + 1: inf
    (0xFF800000, 0x7F7FFFFF),  # -inf + maxVal: -inf
    (0x80000000, 0x80000000),  # -0 + -0: -0
    (0x00000000, 0x80000000),  # +0 + -0: +0
    (0x3F800000, 0xBF800000),  # 1 + -1: +0
    (0x00000001, 0x00000001),  # the smallest subnormal twice: kept, no flush
    (0x00400000, 0x00400000),  # two subnormals giving the smallest normal
    (0x80000001, 0x00000000),  # a negative subnormal + 0: kept
    (0x7FC00000, 0x3F800000),  # NaN + 1: NaN
    (0x3F800000, 0xFFC00001),  # 1 + NaN: NaN
    (0x3DCCCCCD, 0x3E4CCCCD),  # 0.1f + 0.2f
    (0x4B800000, 0x3F800000),  # 2^24 + 1: a tie, to even (2^24)
    (0x4B800001, 0x3F800000),  # (2^24 + 2) + 1: a tie, to even (up)
]


def main():
    rng = random.Random(20261029)
    cases = list(SPECIAL)
    while len(cases) < 600:
        cases.append((rand_pat(rng), rand_pat(rng)))
    rows = []
    for x, y in cases:
        a, b = ref_exact(x, y), ref_numpy(x, y)
        assert a == b, (hex(x), hex(y), a, b)
        rows.append((x, y, a))
    print("import TVA")
    print()
    print("/-! r-vecadd, round 2, third filing: `TVA.FloatV.add` on float32 against two references")
    print("(numpy's float32 addition and an exact rounding of the rational sum), generated by")
    print("`f32add.py`: 21 chosen cases and 579 random ones. `none` stands for a NaN result. -/")
    print()
    print("open TVA")
    print()
    print("def cases : List (Nat × Nat × Option Nat) := [")
    body = []
    for x, y, r in rows:
        rr = "none" if r is None else "some 0x%08X" % r
        body.append("  (0x%08X, 0x%08X, %s)" % (x, y, rr))
    print(",\n".join(body))
    print("]")
    print()
    print("def agrees : Nat × Nat × Option Nat → Bool")
    print("  | (x, y, r) =>")
    print("    let s : F32 := FloatV.add (FloatV.ofPat x) (FloatV.ofPat y)")
    print("    match r with")
    print("    | none => s.isNaN")
    print("    | some p => s.pat == p")
    print()
    print("#eval cases.length")
    print("#eval (cases.filter (fun c => !agrees c)).length")
    print("#eval (cases.filter (fun c => !agrees c)).take 5")


if __name__ == "__main__":
    main()
